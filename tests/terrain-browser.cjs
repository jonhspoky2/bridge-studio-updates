/* Browser integration: Terrain editor -> save/load -> Play -> WARPGAME HTML. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {execFileSync}=require('node:child_process');
const {chromium}=require('playwright');
(async()=>{
 const built=path.join(os.tmpdir(),'bridge-terrain-integration.html');
 execFileSync('python3',[path.join(__dirname,'../tools/build_studio.py'),'--output',built]);
 const editor=await fs.readFile(built);
 const three=await fs.readFile(require.resolve('three/build/three.min.js'));
 const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox']});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:900},acceptDownloads:true});
  let exported=null;
  await context.route('**/*',route=>{
   const u=new URL(route.request().url());
   if(u.pathname==='/exported.html'&&exported)return route.fulfill({contentType:'text/html; charset=utf-8',body:exported});
   if(u.pathname.endsWith('/studio.html'))return route.fulfill({contentType:'text/html; charset=utf-8',body:editor});
   if(u.pathname.endsWith('/three.min.js')||u.pathname.endsWith('/r128/three.min.js'))return route.fulfill({contentType:'text/javascript',body:three});
   if(u.pathname.includes('/Playding/js/auth.js'))return route.fulfill({contentType:'text/javascript',body:''});
   if(u.hostname!=='127.0.0.1')return route.abort('internetdisconnected');
   return route.fulfill({status:404,body:'not found'});
  });
  const page=await context.newPage();
  await page.goto('http://127.0.0.1:41437/test/studio.html');
  await page.waitForFunction(()=>typeof window.__bridgeQA==='function');
  const start=await page.evaluate(()=>window.__bridgeQA().project);
  assert.equal(start.terrain,undefined);
  await page.click('#terrainDemo');
  const before=await page.evaluate(()=>window.__bridgeQA().project);
  assert.equal(before.terrain.chunks.length,2);
  assert.ok(before.objects.some(o=>o.type==='spawn'&&o.position[0]===-8));
  await page.click('#undoBtn');
  assert.deepEqual(await page.evaluate(()=>window.__bridgeQA().project),start,'one Undo restores whole scene');
  await page.click('#redoBtn');
  assert.deepEqual(await page.evaluate(()=>window.__bridgeQA().project),before,'Redo restores terrain and spawn');
  const saving=page.waitForEvent('download');
  await page.click('#saveProject');
  const saved=JSON.parse(await fs.readFile(await (await saving).path(),'utf8'));
  assert.deepEqual(saved.terrain,before.terrain,'rwscene download preserves terrain');
  await page.locator('#projectInput').setInputFiles({name:'terrain-test.rwscene',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
  await page.waitForFunction(()=>window.__bridgeQA().project.terrain?.chunks?.length===2);
  const loaded=await page.evaluate(()=>window.__bridgeQA().project);
  assert.deepEqual(loaded.terrain,before.terrain,'rwscene load preserves heights');
  await page.click('#btnPlay');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('3D-кадр'),{timeout:15000});
  const frame=await (await page.locator('#playFrame').elementHandle()).contentFrame();
  await frame.waitForFunction(()=>window.__bridgeDebugState&&window.__bridgeDebugState().grounded);
  const initial=await frame.evaluate(()=>window.__bridgeDebugState());
  assert.equal(initial.terrainChunks,2);
  assert.ok(initial.firstDt>=0&&initial.firstDt<=.05,'first animation delta must not be negative');
  assert.ok(initial.minTerrainClearance>=-1e-6,'player must never tunnel below terrain');
  assert.ok(Math.abs(initial.position[1]-initial.terrainY)<.1,'starts on terrain');
  await frame.evaluate(()=>window.dispatchEvent(new KeyboardEvent('keydown',{code:'KeyD',key:'d'})));
  await frame.waitForFunction(()=>window.__bridgeDebugState().position[0]>1,{timeout:15000});
  await frame.evaluate(()=>window.dispatchEvent(new KeyboardEvent('keyup',{code:'KeyD',key:'d'})));
  await frame.waitForFunction(()=>window.__bridgeDebugState().grounded);
  const traversed=await frame.evaluate(()=>window.__bridgeDebugState());
  assert.ok(Math.abs(traversed.position[1]-traversed.terrainY)<.15,'walks across tile seam on visible slope');
  await page.click('#btnStop');
  assert.deepEqual(await page.evaluate(()=>window.__bridgeQA().project),loaded,'Stop does not modify editor project');
  await page.selectOption('#exportProfile','warpgame');
  const exporting=page.waitForEvent('download');
  await page.click('#btnBuild');
  const download=await exporting;
  exported=await fs.readFile(await download.path(),'utf8');
  assert.ok(Buffer.byteLength(exported,'utf8')<=3000000,'WARPGAME size budget');
  assert.ok(exported.includes('"terrain":{"version":1'),'terrain serialized into export');
  const game=await context.newPage();
  await game.goto('http://127.0.0.1:41437/exported.html');
  await game.waitForFunction(()=>window.__bridgeDebugState&&window.__bridgeDebugState().terrainChunks===2);
  await game.waitForFunction(()=>window.__bridgeDebugState().grounded);
  const launched=await game.evaluate(()=>window.__bridgeDebugState());
  assert.ok(Math.abs(launched.position[1]-launched.terrainY)<.1,'exported surface matches Play');
  console.log('Terrain browser integration OK:',{size:Buffer.byteLength(exported),chunks:launched.terrainChunks,walkedTo:traversed.position});
  await context.close();
 }finally{await browser.close();}
})().catch(err=>{console.error(err);process.exitCode=1;});
